      '## 6. Window Functions (MySQL 8.0+)',
      '',
      'Window functions perform calculations across a set of table rows without collapsing them.',
      '',
      '### Ranking Functions',
      '',
      '```sql',
      '-- ROW_NUMBER: unique sequential number',
      '-- RANK: same rank for ties, gaps after ties',
      '-- DENSE_RANK: same rank for ties, no gaps',
      'SELECT',
      '  name,',
      '  salary,',
      '  department,',
      '  ROW_NUMBER() OVER (PARTITION BY department ORDER BY salary DESC) AS row_num,',
      '  RANK()       OVER (PARTITION BY department ORDER BY salary DESC) AS rnk,',
      '  DENSE_RANK() OVER (PARTITION BY department ORDER BY salary DESC) AS dense_rnk',
      'FROM employees;',
      '',
      '-- Get top earner per department:',
      'SELECT * FROM (',
      '  SELECT',
      '    *,',
      '    RANK() OVER (PARTITION BY department ORDER BY salary DESC) AS rnk',
      '  FROM employees',
      ') ranked',
      'WHERE rnk = 1;',
      '```',
      '',
      '### Offset Functions',
      '',
      '```sql',
      '-- LAG: access a previous row value',
      '-- LEAD: access a next row value',
      'SELECT',
      '  order_date,',
      '  revenue,',
      '  LAG(revenue, 1, 0)  OVER (ORDER BY order_date) AS prev_revenue,',
      '  LEAD(revenue, 1, 0) OVER (ORDER BY order_date) AS next_revenue,',
      '  revenue - LAG(revenue) OVER (ORDER BY order_date) AS daily_change',
      'FROM daily_sales;',
      '',
      '-- FIRST_VALUE / LAST_VALUE',
      'SELECT',
      '  name,',
      '  salary,',
      '  FIRST_VALUE(salary) OVER (PARTITION BY department ORDER BY hire_date) AS first_hire_salary,',
      '  LAST_VALUE(salary)  OVER (',
      '    PARTITION BY department',
      '    ORDER BY hire_date',
      '    ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING',
      '  ) AS last_hire_salary',
      'FROM employees;',
      '```',
