      '',
      '-- JSON_REMOVE: delete a key',
      'UPDATE products',
      'SET attributes = JSON_REMOVE(attributes, \'$.warranty\')',
      'WHERE id = 1;',
      '',
      '-- JSON_REPLACE: update only (won\'t create new keys)',
